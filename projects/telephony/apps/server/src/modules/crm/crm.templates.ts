function template(name: string, fields: Field[], notes: unknown[][], validations: Sheet['validations'] = []) {
 const headers = fields.map(f=>f[1]==='必填'?'* '+f[0]:f[0]);
 const guide=common.map(row=>row[0]==='必填标记'&&name!=='客户资料'?[row[0],'表头带 * 的字段必须填写；其余字段按对应填写规则填写。',row[2]]:row);
 return Buffer.from(multiSheetWorkbook([
  {name,headers,kind:'data',blankRows:25,exampleRow:fields.map((f,i)=>i===0?'【示例】（不导入）\n'+f[2]+'\n第3行起填写':f[2]),validations,columnHints:fields.map((f,column)=>({column,text:f[1]+'：'+f[3]}))},
  {name:'填写说明',headers:['说明项','具体说明','操作范围'],rows:[...guide,...notes],widths:[18,64,14],kind:'notes'},
  {name:'填写示例',headers,rows:[fields.map(f=>f[2])],kind:'example'},
  {name:'字段说明',headers:['字段名称','是否必填','格式示例','填写规则'],rows:fields.map((f,i)=>[headers[i],...f.slice(1)]),widths:[22,20,28,58],kind:'dictionary'},
 ]));
}
